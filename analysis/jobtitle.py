# 备用动态分类：当静态 RULES 全部未命中时，尝试从标题中提取有意义的类别词
_FALLBACK_PATTERNS = [
    (re.compile(r'(python|java|go|rust|c\+\+|php|ruby)', re.I), '后端开发'),
    (re.compile(r'(react|vue|angular|node\.js|typescript)', re.I), 'Web/前端'),
    (re.compile(r'(django|flask|fastapi|spring|tornado)', re.I), '后端开发'),
    (re.compile(r'(mysql|postgresql|mongodb|redis|oracle)', re.I), '数据/AI'),
    (re.compile(r'(docker|kubernetes|k8s|jenkins|devops)', re.I), '运维/DevOps'),
]


def classify(post_title):
    """使用 RULES 为单个职位标题分配类别标签（数据驱动）。

    匹配策略:
      1. 静态 RULES 精确关键词匹配
      2. 未命中时尝试 _FALLBACK_PATTERNS 正则匹配
      3. 全部未命中返回 "其他岗位"
    """
    if not post_title:
        return '其他岗位'
    title_lower = post_title.lower()
    for keyword, category in RULES:
        if keyword.lower() in title_lower:
            return category
    # 动态备用匹配
    for pattern, category in _FALLBACK_PATTERNS:
        if pattern.search(title_lower):
            return category
    return '其他岗位'


def get_post():
    db = sqlite3.connect(config.DB_PATH)
    try:
        cursor = db.cursor()
        cursor.execute("select post from data")
        return cursor.fetchall()
    except Exception as e:
        print('query failed:', e)
        return []
    finally:
        db.close()


def jobtitlefun():
    rows = get_post()
    categories = [classify(row[0]) for row in rows if row[0]]
    # 无有效职位标题时返回空列表（DataFrame([]) 取列 0 会 KeyError）
    if not categories:
        return []

    counts = DataFrame(categories)[0].value_counts()

    list_all = []
    for category, count in zip(counts.index, counts):
        list_all.append([category, int(count)])
    return list_all


if __name__ == '__main__':
    print(jobtitlefun())
